#!/usr/bin/env python3
"""The per-machine reference: what earlier scans found, and what was created.

Lives in <data root>/hotkey-builder/<hostname>/ (data_root() in hkb_common
explains the resolution). JSON files are written by the other scripts;
README.md is rendered from them for humans and for the next session.

  reference.py path                         print the folder and which rule chose it
  reference.py status                       what exists, how old each scan is
  reference.py log --key KEY_PAUSE --route kde --action "types: claude + Enter" \
                   --undo "bind_kde.py --unbind type_claude"
  reference.py render                       (re)write README.md
"""

import argparse
import datetime
import json
import os
import socket
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hkb_common import data_root, host_dir, load_json, now, save_json  # noqa: E402

FILES = ["environment.json", "devices.json", "keys.json", "bindings.json", "claims.json", "shortcuts.json"]


def age(iso):
    try:
        t = datetime.datetime.fromisoformat(iso)
        d = datetime.datetime.now(t.tzinfo) - t
        return "%dd ago" % d.days if d.days else "%dh ago" % (d.seconds // 3600)
    except (TypeError, ValueError):
        return "?"


def status():
    root, rule = data_root()
    print("reference: %s  (root chosen by: %s)" % (host_dir(), rule))
    for f in FILES:
        data = load_json(f)
        if data is None:
            print("  %-18s missing" % f)
            continue
        stamp = (data.get("checked_at") or data.get("scanned_at") or data.get("updated_at")
                 if isinstance(data, dict) else None)
        print("  %-18s %s" % (f, ("scanned " + age(stamp)) if stamp else "%d entries" % len(data)))


def log(args):
    items = load_json("shortcuts.json", []) or []
    items = [i for i in items if not (i["key"] == args.key and i.get("device") == args.device)]
    items.append({"key": args.key, "device": args.device, "route": args.route, "action": args.action,
                  "undo": args.undo, "verified": args.verified, "created_at": now()})
    print("logged in " + save_json("shortcuts.json", items))
    render()


def render():
    env = load_json("environment.json") or {}
    dev = load_json("devices.json") or {}
    keys = load_json("keys.json") or {}
    claims = load_json("claims.json", []) or []
    shortcuts = load_json("shortcuts.json", []) or []
    s = env.get("session", {})
    out = ["# Hotkey reference: %s" % socket.gethostname(), "",
           "Generated by the hotkey-builder plugin, %s. Edit `claims.json` by hand to reserve keys; "
           "everything else is rewritten by the scans." % now(), ""]
    if env:
        rec = env.get("recommendation", {})
        out += ["## Environment (checked %s)" % env.get("checked_at"), "",
                "- Session: %s / %s %s, %s" % (s.get("session_type"), s.get("desktop"),
                                               s.get("plasma") or s.get("gnome_shell") or "", s.get("distro")),
                "- Layouts: %s" % ", ".join(env.get("layouts", [])),
                "- Injector: %s" % (rec.get("injector") or {}).get("choice"),
                "- Interceptor: %s" % (rec.get("interceptor") or {}).get("choice"),
                "- Desktop binding: %s" % (rec.get("desktop_binding") or {}).get("choice"), ""]
    if dev:
        out += ["## Devices (scanned %s)" % dev.get("scanned_at"), "", "| VID:PID | Class | Bus | Node | Name |",
                "| --- | --- | --- | --- | --- |"]
        for d in dev.get("input_devices", []):
            if d["class"] in ("keyboard", "buttons", "pointer"):
                out.append("| %s:%s | %s | %s | %s | %s |" % (d["vid"], d["pid"], d["class"], d["bus"], d["event"],
                                                             d["name"]))
        usb = [u for u in dev.get("usb", []) if not u["root_hub"]]
        if usb:
            out += ["", "USB: " + "; ".join("%s:%s %s" % (u["vid"], u["pid"], u["description"]) for u in usb)]
        out.append("")
    if keys.get("confirmed"):
        out += ["## Keys confirmed by pressing", ""]
        for ident, ks in keys["confirmed"].items():
            out.append("- **%s**: %s" % (ident, ", ".join("%s (scancode %s)" % (k, v.get("scancode"))
                                                          for k, v in sorted(ks.items()))))
        out.append("")
    if claims:
        out += ["## Manual reservations (`claims.json`)", ""]
        out += ["- %s: %s" % (c.get("evdev") or c.get("key"), c.get("action")) for c in claims]
        out.append("")
    out += ["## Shortcuts created", ""]
    if shortcuts:
        out += ["| Key | Device | Route | Does | Verified | Undo |", "| --- | --- | --- | --- | --- | --- |"]
        for i in shortcuts:
            out.append("| %s | %s | %s | %s | %s | `%s` |" % (i["key"], i.get("device") or "any", i["route"],
                                                             i["action"], i.get("verified") or "no", i.get("undo")))
    else:
        out.append("None yet.")
    path = os.path.join(host_dir(), "README.md")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("rendered " + path)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("path")
    sub.add_parser("status")
    sub.add_parser("render")
    lg = sub.add_parser("log")
    lg.add_argument("--key", required=True)
    lg.add_argument("--route", required=True)
    lg.add_argument("--action", required=True)
    lg.add_argument("--undo", required=True)
    lg.add_argument("--device")
    lg.add_argument("--verified", help="how it was verified, e.g. 'physical press 2026-10-22'")
    args = ap.parse_args()
    if args.cmd == "path":
        root, rule = data_root()
        print(host_dir())
        print("rule: " + rule, file=sys.stderr)
    elif args.cmd == "status":
        status()
    elif args.cmd == "render":
        render()
    else:
        log(args)


if __name__ == "__main__":
    main()
